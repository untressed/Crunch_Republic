const defaultDishPhoto = '/assets/dishes/burger_veg.webp';

/**
 * Returns the authentic high-resolution food photograph for any dish:
 * 1. Checks if dish.image exists and fixes outdated .svg or .jpg references to .webp.
 * 2. Uses exact dish name matching to find the high-res food photo.
 * 3. Falls back to smart keyword detection.
 */
export function getDishImage(dish) {
  if (!dish) return defaultDishPhoto;

  const rawImage = typeof dish === 'string' ? dish : dish?.image;
  const name = (typeof dish === 'string' ? '' : dish?.name || '').toLowerCase().trim();
  const categoryName = (typeof dish === 'string' ? '' : dish?.categoryName || (dish?.category && dish?.category.name) || '').toLowerCase().trim();

  // If dish has a valid uploaded or external image that is NOT a cartoon SVG
  if (rawImage && typeof rawImage === 'string' && rawImage.trim() !== '') {
    const trimmed = rawImage.trim();

    // If it's a cartoon SVG, override with actual real photo
    if (!trimmed.endsWith('.svg')) {
      // Auto-correct .jpg/.png to .webp for local assets
      if (trimmed.startsWith('/assets/dishes/') && (trimmed.endsWith('.jpg') || trimmed.endsWith('.png'))) {
        return trimmed.replace(/\.(jpg|png)$/, '.webp');
      }
      return trimmed;
    }
  }

  // 1. Exact Name Match
  if (name && dishPhotoMap[name]) {
    return dishPhotoMap[name];
  }

  // 2. Keyword-based matching
  const target = `${name} ${categoryName}`;

  const isEgg = target.includes('egg');
  const isNonVeg = target.includes('non-veg') || target.includes('non veg') || target.includes('chicken');

  if (target.includes('schezwan rice')) return isNonVeg ? '/assets/dishes/rice_schezwan_chicken.webp' : (isEgg ? '/assets/dishes/rice_schezwan_egg.webp' : '/assets/dishes/rice_schezwan_veg.webp');
  if (target.includes('fried rice')) return isNonVeg ? '/assets/dishes/rice_fried_chicken.webp' : (isEgg ? '/assets/dishes/rice_fried_egg.webp' : '/assets/dishes/rice_fried_veg.webp');
  if (target.includes('burnt garlic rice')) return isNonVeg ? '/assets/dishes/rice_burnt_garlic_chicken.webp' : (isEgg ? '/assets/dishes/rice_burnt_garlic_egg.webp' : '/assets/dishes/rice_burnt_garlic_veg.webp');
  if (target.includes('rice') && target.includes('bowl')) return '/assets/dishes/chole_rice_bowl.webp';

  if (target.includes('chilli garlic noodle')) return isNonVeg ? '/assets/dishes/noodles_chilli_garlic_chicken.webp' : (isEgg ? '/assets/dishes/noodles_chilli_garlic_egg.webp' : '/assets/dishes/noodles_chilli_garlic_veg.webp');
  if (target.includes('singapuri noodle')) return isNonVeg ? '/assets/dishes/noodles_singapuri_chicken.webp' : (isEgg ? '/assets/dishes/noodles_singapuri_egg.webp' : '/assets/dishes/noodles_singapuri_veg.webp');
  if (target.includes('hakka noodle')) return isNonVeg ? '/assets/dishes/noodles_hakka_chicken.webp' : (isEgg ? '/assets/dishes/noodles_hakka_egg.webp' : '/assets/dishes/noodles_hakka_veg.webp');
  if (target.includes('schezwan noodle')) return isNonVeg ? '/assets/dishes/noodles_schezwan_chicken.webp' : (isEgg ? '/assets/dishes/noodles_schezwan_egg.webp' : '/assets/dishes/noodles_schezwan_veg.webp');
  if (target.includes('noodle') || target.includes('chowmein')) return isNonVeg ? '/assets/dishes/noodles_street_chicken.webp' : (isEgg ? '/assets/dishes/noodles_street_egg.webp' : '/assets/dishes/noodles_street_veg.webp');

  if (target.includes('chilli paneer')) return '/assets/dishes/chilli_paneer.webp';
  if (target.includes('manchurian')) return target.includes('chicken') ? '/assets/dishes/chicken_manchurian.webp' : '/assets/dishes/manchurian_veg.webp';
  if (target.includes('chilli potato') && target.includes('honey')) return '/assets/dishes/honey_chilli_potato.webp';
  if (target.includes('chilli potato')) return '/assets/dishes/chilli_potato.webp';
  if (target.includes('crispy corn')) return '/assets/dishes/crispy_corn.webp';
  if (target.includes('dynamite chicken')) return '/assets/dishes/dynamite_chicken.webp';
  if (target.includes('korean bbq')) return '/assets/dishes/korean_bbq_chicken.webp';
  if (target.includes('chicken popcorn') || target.includes('thai chicken')) return '/assets/dishes/thai_chicken_popcorn.webp';
  if (target.includes('chicken tender')) return '/assets/dishes/chicken_tenders.webp';

  if (target.includes('dumpling') || target.includes('momo')) return target.includes('non') || target.includes('chicken') ? '/assets/dishes/nonveg_dumplings.webp' : '/assets/dishes/veg_dumplings.webp';
  if (target.includes('wonton')) return '/assets/dishes/mutton_wontons.webp';

  if (target.includes('malai chaap')) return '/assets/dishes/malai_chaap.webp';
  if (target.includes('paneer tikka')) return '/assets/dishes/paneer_tikka.webp';
  if (target.includes('tandoori chaap')) return '/assets/dishes/tandoori_chaap.webp';
  if (target.includes('seekh kebab')) return target.includes('mutton') ? '/assets/dishes/mutton_seekh_kebab.webp' : '/assets/dishes/chicken_seekh_kebab.webp';
  if (target.includes('spring roll')) return '/assets/dishes/spring_roll.webp';
  if (target.includes('cigar roll')) return '/assets/dishes/cheese_cigar_roll.webp';

  if (target.includes('sweet corn soup')) return '/assets/dishes/sweet_corn_soup.webp';
  if (target.includes('hot & sour') || target.includes('hot and sour')) return '/assets/dishes/hot_sour_soup.webp';
  if (target.includes('mushroom soup')) return '/assets/dishes/mushroom_soup.webp';
  if (target.includes('kharodey')) return '/assets/dishes/mutton_kharodey_soup.webp';
  if (target.includes('soup')) return '/assets/dishes/chicken_soup.webp';

  if (target.includes('chole bhature')) return target.includes('paneer') ? '/assets/dishes/paneer_chole_bhature.webp' : '/assets/dishes/chole_bhature.webp';
  if (target.includes('poori sabzi')) return '/assets/dishes/poori_sabzi.webp';

  if (target.includes('tea')) return '/assets/dishes/tea.webp';
  if (target.includes('cappuccino')) return '/assets/dishes/cappuccino_special.webp';
  if (target.includes('coffee') && target.includes('hazelnut') && target.includes('hot')) return '/assets/dishes/coffee_hazelnut_hot.webp';
  if (target.includes('coffee') && target.includes('cold')) return '/assets/dishes/mocktail_cold_coffee.webp';
  if (target.includes('coffee')) return '/assets/dishes/coffee.webp';

  if (target.includes('samosa')) return '/assets/dishes/samosa.webp';
  if (target.includes('bread pakoda') || target.includes('pakoda')) return '/assets/dishes/bread_pakoda.webp';
  if (target.includes('jalebi')) return target.includes('rabri') ? '/assets/dishes/rabri_jalebi.webp' : '/assets/dishes/jalebi.webp';
  if (target.includes('imarti')) return target.includes('rabri') ? '/assets/dishes/rabri_imarti.webp' : '/assets/dishes/imarti.webp';
  if (target.includes('aloo patties')) return '/assets/dishes/aloo_patties.webp';
  if (target.includes('paneer patties') || target.includes('patties')) return '/assets/dishes/paneer_patties.webp';

  if (target.includes('animal') || target.includes('animal fries')) return '/assets/dishes/fries_animal.webp';
  if (target.includes('butter chicken fries')) return '/assets/dishes/fries_butter_chicken.webp';
  if (target.includes('cheesy fries')) return '/assets/dishes/fries_cheesy.webp';
  if (target.includes('peri peri') && target.includes('fries')) return '/assets/dishes/fries_periperi.webp';
  if (target.includes('fries')) return '/assets/dishes/fries_salted.webp';

  if (target.includes('corn dog') || target.includes('corndog')) {
    if (target.includes('ramen') || target.includes('wai wai')) return '/assets/dishes/corndog_ramen.webp';
    if (target.includes('potato') || target.includes('fry guy')) return '/assets/dishes/corndog_potato.webp';
    if (target.includes('chicken') || target.includes('chick pick')) return '/assets/dishes/corndog_chicken.webp';
    return '/assets/dishes/corndog_classic.webp';
  }

  if (target.includes('burger')) {
    if (target.includes('paneer')) return '/assets/dishes/burger_paneer.webp';
    if (target.includes('chicken') || target.includes('non-veg')) return '/assets/dishes/burger_chicken.webp';
    return '/assets/dishes/burger_veg.webp';
  }

  if (target.includes('wrap')) {
    if (target.includes('chicken') || target.includes('non-veg')) return '/assets/dishes/wrap_chicken.webp';
    return '/assets/dishes/wrap_veg.webp';
  }

  if (target.includes('sandwich') || target.includes('kulcha')) {
    if (target.includes('bahubali')) return '/assets/dishes/sandwich_bahubali.webp';
    if (target.includes('kulcha')) return '/assets/dishes/kulcha_stuffed.webp';
    if (target.includes('chicken') || target.includes('non-veg')) return '/assets/dishes/sandwich_chicken.webp';
    return '/assets/dishes/sandwich_veg.webp';
  }

  if (target.includes('macaroni')) return '/assets/dishes/desi_macaroni.webp';
  if (target.includes('pasta')) {
    if (target.includes('alfredo')) {
      return target.includes('non-veg') || target.includes('chicken') ? '/assets/dishes/pasta_alfredo_chicken.webp' : '/assets/dishes/pasta_alfredo_veg.webp';
    }
    if (target.includes('red sauce') || target.includes('arrabbiata')) {
      return target.includes('non-veg') || target.includes('chicken') ? '/assets/dishes/pasta_red_chicken.webp' : '/assets/dishes/pasta_red_veg.webp';
    }
    return target.includes('non-veg') || target.includes('chicken') ? '/assets/dishes/pasta_makhani_chicken.webp' : '/assets/dishes/pasta_makhani_veg.webp';
  }

  if (target.includes('maggie')) {
    if (target.includes('cheesy')) return '/assets/dishes/maggie_cheesy.webp';
    if (target.includes('korean')) return '/assets/dishes/maggie_korean.webp';
    if (target.includes('makhani')) return '/assets/dishes/maggie_makhani.webp';
    if (target.includes('egg')) return '/assets/dishes/maggie_egg.webp';
    return '/assets/dishes/maggie_veg.webp';
  }

  if (target.includes('byob') || target.includes('chips')) {
    if (target.includes('masala chaska') || target.includes('masala')) return '/assets/dishes/byob_masala.webp';
    if (target.includes('cheesy')) return '/assets/dishes/byob_cheesy.webp';
    if (target.includes('meaty') || target.includes('meat')) return '/assets/dishes/byob_meat.webp';
    if (target.includes('special')) return '/assets/dishes/byob_special.webp';
    return '/assets/dishes/byob_custom.webp';
  }

  if (target.includes('mojito') || target.includes('mocktail')) {
    if (target.includes('blue ocean')) return '/assets/dishes/mocktail_blue_ocean.webp';
    if (target.includes('strawberry')) return '/assets/dishes/mocktail_strawberry.webp';
    if (target.includes('watermelon')) return '/assets/dishes/mocktail_watermelon.webp';
    if (target.includes('mango')) return '/assets/dishes/mocktail_mango.webp';
    if (target.includes('piña colada') || target.includes('pina colada')) return '/assets/dishes/mocktail_pinacolada.webp';
    if (target.includes('jaljeera')) return '/assets/dishes/mocktail_jaljeera.webp';
    return '/assets/dishes/mocktail_mojito.webp';
  }

  if (target.includes('shake')) {
    if (target.includes('oreo')) return '/assets/dishes/shake_oreo.webp';
    if (target.includes('peanut butter')) return '/assets/dishes/shake_peanut_butter.webp';
    if (target.includes('matcha')) return '/assets/dishes/shake_matcha.webp';
    return '/assets/dishes/shake_chocolate.webp';
  }

  return defaultDishPhoto;
}
